export function getRegistrationTranslation(language: string): RegTranslationStrings {
  const specific = regTranslations[language];
  if (!specific) {
    return baseEnglish;
  }
  return {
    ...baseEnglish,
    ...specific,
    months: specific.months || baseEnglish.months,
  };
}
